export function getCatalogProducts(): Product[] {
  return CATALOG_PRODUCTS.map((p) => ({
    id: p.id,
    name: p.name,
    slug: p.slug,
    subtitle: p.subtitle,
    category: p.category,
    sku: p.sku,
    stock: p.stock,
    description: p.description,
    images: p.images,
    length: p.length,
    width: p.width,
    colors: p.colors,
    priceRegular: p.priceRegular,
    priceSale: p.priceSale,
    productionTime: p.productionTime,
    availability: p.availability,
    customizationPrice: p.customizationPrice,
    createdAt: p.createdAt,
    updatedAt: p.updatedAt,
  }))
}

export function getCatalogProductBySlug(slug: string): CatalogItem | undefined {
  return CATALOG_PRODUCTS.find((p) => p.slug === slug)
}

export function getCatalogProductById(id: string): CatalogItem | undefined {
  return CATALOG_PRODUCTS.find((p) => p.id === id)
}
